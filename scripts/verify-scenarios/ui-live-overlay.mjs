/* global document, getComputedStyle */
import { createBot, appendBotTurn } from '../../packages/core/src/index.ts'
import { controlsUsable, deckInline, deckOffset, describeBlocks, flowGeometry, measureChat, packedBlocks, settleAnimations, stackBounded } from './lib/chat-layout.mjs'
import { appPreview, cancelDrag, constrainChat, dragAcross, dragBy, dragTo, expectPainted, grab, pngFrame, secondPointer, sendEvents, showWebFrame, sizeWindow, switchAway, toggleSidebar, withRefusedCapture } from './lib/frame-fixture.mjs'

const BOT = 'Live overlay'
const URL = 'https://example.test/live'
const FAR = { x: 2000, y: 1500 }

export async function run(page, { app, paths, expect, openActivity }) {
  const bot = await createBot(paths, { name: BOT, purpose: '' })
  const other = await createBot(paths, { name: 'Other overlay lane', purpose: '' })
  const solo = await createBot(paths, { name: 'App only lane', purpose: '' })
  for (const role of ['user', 'assistant']) await appendBotTurn(paths, bot.id, { role, text: `Overlay geometry ${role}`, at: new Date().toISOString() })
  const resize = (width, height) => sizeWindow(app, page, expect, width, height)
  const row = (name) => page.locator('.bots-row', { hasText: name })
  const sidebar = (open) => toggleSidebar(page, open)
  await resize(1400, 900)
  await page.reload()
  await openActivity(page, 'bots'); await row(BOT).click()
  const lane = `bot-${bot.id}`, soloLane = `bot-${solo.id}`
  const frame = pngFrame({ width: 1280, height: 800 })
  const plain = pngFrame({ width: 640, height: 400, paint: () => [40, 90, 220] })
  const settle = () => settleAnimations(page)
  await settle()
  const baseline = await flowGeometry(page)
  await showWebFrame(app, { lane, url: URL, frame })

  const card = page.getByTestId('preview-card'), deck = page.getByTestId('preview-deck'), cards = deck.locator('.preview-deck-card')
  await expectPainted(card, frame, expect)
  await expect(page.getByTestId('live-address')).toHaveCount(0)
  expect(await card.evaluate(node => getComputedStyle(node).animationName)).toBe('preview-card-in')
  await settle()
  expect(await flowGeometry(page)).toEqual(baseline)

  const relative = () => deckOffset(deck)
  const inlineLeft = () => deck.evaluate(node => node.style.left)
  const packed = async (label) => expect(packedBlocks(await measureChat(page)).reasons, label).toEqual([])
  const bounded = () => expect.poll(() => stackBounded(deck)).toBe(true)
  const idle = () => expect(deck).not.toHaveAttribute('data-dragging')
  const dragging = () => expect(deck).toHaveAttribute('data-dragging', '')
  const pointerId = () => deck.evaluate(node => Number(node.dataset.pointer))
  await deck.evaluate(node => node.addEventListener('pointerdown', event => { node.dataset.pointer = event.pointerId }))
  const near = (value, target) => expect(Math.abs(value - target)).toBeLessThan(1.5)
  const visible = async () => { await expect(card).toBeVisible(); await settle() }
  const anchored = await relative()
  await openActivity(page, 'list'); await expect(card).toBeHidden()
  await openActivity(page, 'bots'); await visible()
  expect(await relative()).toEqual(anchored)
  const anchorSurvives = async () => {
    for (const width of [1100, 1600, 1400]) { await resize(width, 900); await expect.poll(async () => (await relative()).right).toBeCloseTo(anchored.right, 0); expect(await inlineLeft()).toBe('') }
  }
  await anchorSurvives()

  await sendEvents(app, [appPreview(lane, ['second', 'third', 'fourth'], frame)])
  await expect(cards).toHaveCount(4)
  await resize(800, 560); await sidebar(false); await settle()
  await bounded(); await packed('untouched four cards at 800x560')
  await resize(1400, 600); await sidebar(true)
  await page.getByTestId('bots-input').fill('one\ntwo\nthree\nfour')
  await bounded(); await packed('untouched four cards at 1400x600 under a draft')
  await page.getByTestId('bots-input').fill('')
  await resize(1400, 900)
  await expect.poll(async () => (await relative()).right).toBeCloseTo(anchored.right, 0)
  expect(await deckInline(deck)).toEqual(['', '', false, false])
  await sendEvents(app, [appPreview(lane, [], frame)])
  await expect(cards).toHaveCount(1)
  await settle()
  const before = await measureChat(page)
  expect(packedBlocks(before).reasons, 'before the drag').toEqual([])
  expect(await flowGeometry(page)).toEqual(baseline)

  for (const [trigger, menu] of [[page.getByTestId('workspace-switcher'), 'workspace-menu'], [page.locator('.bots-chat').getByTestId('model-picker'), 'model-picker-menu']]) {
    await trigger.click()
    await expect(page.getByTestId(menu)).toBeVisible()
    await packed(`${menu} open`)
    await grab(page, card); await page.mouse.up()
    await expect(page.getByTestId(menu)).toHaveCount(0)
    expect(await inlineLeft()).toBe('')
  }
  await grab(page, card)
  await page.mouse.move(before.card.left + 80, before.card.top + 30, { steps: 4 })
  await dragging(); expect(await inlineLeft()).not.toBe('')
  await page.keyboard.press('Escape'); await page.mouse.up()
  await idle(); expect(await inlineLeft()).toBe('')
  expect(await relative()).toEqual(anchored)
  await anchorSurvives(); await settle()
  await packed('after cancelling the first drag')

  const drag = await dragAcross(page, card, async () => expect(await flowGeometry(page)).toEqual(baseline))
  await expect(card).toBeVisible()
  await expect(card.locator('canvas')).toHaveAttribute('data-painted', '')
  await expect(page.getByTestId('bots-input')).toBeVisible()
  const after = await measureChat(page)
  expect(packedBlocks(after).reasons, 'after the drag').toEqual([])
  expect(Math.abs(after.card.left - (before.card.left - before.card.width))).toBeLessThan(2)
  expect(Math.abs(after.card.top - (before.card.top + before.card.height))).toBeLessThan(2)
  expect(await flowGeometry(page)).toEqual(baseline)
  expect(await page.evaluate(() => document.getSelection().toString())).toBe('')
  const origin = await card.boundingBox()
  await page.mouse.move(500, 500)
  expect(await card.boundingBox()).toEqual(origin)
  for (const cancellation of ['Escape', 'pointercancel', 'lostpointercapture', 'blur', 'tab']) {
    await grab(page, card)
    await page.mouse.move(origin.x + 80, origin.y + 30)
    if (cancellation === 'tab') { await switchAway(page); await expect(card).toBeHidden(); await openActivity(page, 'bots'); await visible() }
    else await cancelDrag(page, deck, cancellation, await pointerId())
    await page.mouse.up()
    expect(await card.boundingBox()).toEqual(origin); await idle()
    expect(await flowGeometry(page)).toEqual(baseline)
  }
  await dragTo(page, card, { x: 0, y: 0 }, 10)
  let clamped = await measureChat(page)
  expect(clamped.card.left).toBeCloseTo(clamped.chat.left, 0)
  expect(clamped.card.top).toBeCloseTo(clamped.chat.top, 0)
  await dragTo(page, card, FAR, 10)
  clamped = await measureChat(page)
  expect(clamped.card.right).toBeCloseTo(clamped.chat.right, 0)
  expect(Math.abs(clamped.card.bottom - clamped.thread.bottom)).toBeLessThanOrEqual(1)
  expect(packedBlocks(clamped).reasons, 'parked at the bottom').toEqual([])
  await idle()
  expect(await flowGeometry(page)).toEqual(baseline)
  const restored = await card.boundingBox()
  for (const [index, testId] of [[1, 'preview-card-collapsed'], [2, 'preview-card-reopen']]) {
    await card.hover(); await card.locator('.preview-card-actions button').nth(index).click()
    await expect(card).toHaveCount(0)
    expect(await flowGeometry(page)).toEqual(baseline)
    await page.getByTestId(testId).click(); await visible()
    expect(await card.boundingBox()).toEqual(restored)
    expect(await flowGeometry(page)).toEqual(baseline)
    await packed(`after ${testId}`)
  }
  const parkedRight = await relative()
  await grab(page, card)
  await page.mouse.move(restored.x + 80, restored.y + 30)
  await resize(1100, 900)
  await dragging(); await bounded()
  const squeezed = await relative()
  expect(squeezed.x).toBeLessThan(parkedRight.x - 200)
  await page.mouse.move(restored.x + 79, restored.y + 30)
  near((await relative()).x, squeezed.x - 1)
  await page.mouse.up()
  await resize(1400, 900)
  await expect.poll(async () => (await relative()).x).toBeCloseTo(squeezed.x - 1, 0)
  await dragTo(page, card, FAR)
  await expect.poll(relative).toEqual(parkedRight)

  await grab(page, card)
  await page.mouse.move(restored.x + 80, restored.y + 30)
  const held = await relative()
  await sendEvents(app, [appPreview(lane, ['second'], frame)])
  await expect(card).toHaveAttribute('data-source', 'app')
  await settle(); await dragging()
  expect(await relative()).toEqual(held)
  await page.mouse.move(restored.x + 100, restored.y + 50)
  expect((await relative()).x).toBeCloseTo(held.x + 20, 0)
  await page.mouse.up()
  await deck.focus()
  for (const [key, source] of [['ArrowRight', 'web'], ['ArrowLeft', 'app'], ['ArrowLeft', 'web']]) { await page.keyboard.press(key); await expect(card).toHaveAttribute('data-source', source) }
  await settle()
  expect(await deck.locator('[data-position="0"]').evaluate(node => getComputedStyle(node).animationName)).toBe('preview-deck-forward')
  expect(await flowGeometry(page)).toEqual(baseline)
  const chosen = await relative()
  for (const width of [1100, 1600, 1400]) {
    await resize(width, 900)
    await expect.poll(async () => packedBlocks(await measureChat(page)).reasons).toEqual([])
    if (width === 1100) await expect.poll(async () => (await relative()).x).toBeLessThan(chosen.x)
  }
  await expect.poll(relative).toEqual(chosen)
  let savedLane
  for (const [index, x] of [[0, 600], [1, 0]]) {
    await dragTo(page, card, { x, y: 0 }, 10)
    savedLane = await relative()
    await sendEvents(app, [appPreview(lane, ['second', ...['third', 'fourth'].slice(0, index + 1)], frame)])
    await expect(cards).toHaveCount(index + 3)
    await settle(); await bounded()
    expect((await relative()).y).toBeCloseTo((index + 2) * 30, 0)
  }
  await sendEvents(app, [appPreview(lane, [], frame)])
  await expect(cards).toHaveCount(1)
  await expect.poll(relative).toEqual(savedLane)
  await row(other.name).click()
  await showWebFrame(app, { lane: `bot-${other.id}`, url: URL, frame })
  await visible(); expect(await inlineLeft()).toBe('')
  await dragAcross(page, card, () => packed('other lane drag'))
  const otherPosition = await relative()
  await row(BOT).click(); await visible()
  expect(await relative()).toEqual(savedLane); await bounded()
  await row(other.name).click(); await visible()
  expect(await relative()).toEqual(otherPosition)
  await row(BOT).click(); await visible()
  await sendEvents(app, [appPreview(lane, ['second', 'third', 'fourth'], frame)])
  await expect(cards).toHaveCount(4)
  await resize(1400, 600); await settle()
  await dragTo(page, card, FAR, 10)
  const parked = await measureChat(page)
  expect(packedBlocks(parked).reasons, 'parked at the bottom of a short window').toEqual([])
  expect(Math.abs(parked.card.bottom - parked.thread.bottom)).toBeLessThanOrEqual(1)
  await grab(page, card); await dragging()
  await page.mouse.move(parked.card.left, parked.card.top, { steps: 6 }); await page.mouse.up()
  expect((await measureChat(page)).card.top).toBeLessThan(parked.card.top - 20)
  await dragTo(page, card, FAR, 10)
  await page.getByTestId('bots-input').fill('one\ntwo\nthree\nfour')
  await expect.poll(async () => (await measureChat(page)).thread.bottom).toBeLessThan(parked.thread.bottom - 40)
  await expect.poll(async () => packedBlocks(await measureChat(page)).reasons, 'composer grew under a parked card').toEqual([])
  await page.getByTestId('bots-input').fill('')
  await expect.poll(async () => (await measureChat(page)).card.top).toBeCloseTo(parked.card.top, 0)
  await resize(1400, 900)
  await expect.poll(async () => packedBlocks(await measureChat(page)).reasons).toEqual([])

  const roomy = await measureChat(page)
  const extra = roomy.chat.height - roomy.thread.height
  try {
    await constrainChat(page, `${Math.round(extra + 150)}px`)
    await expect.poll(async () => (await measureChat(page)).thread.height).toBeLessThan(160)
    await settle(); await bounded()
    const tight = await measureChat(page)
    expect(packedBlocks(tight).reasons, 'four cards in a 150px thread').toEqual([])
    expect(tight.card.height).toBeLessThan(roomy.card.height - 50)
    expect(await controlsUsable(card)).toBe(true)
    await constrainChat(page, `${Math.round(extra + 30)}px`)
    await expect.poll(async () => (await measureChat(page)).suspended).toBe(true)
    await expect(card).toBeHidden()
    await page.mouse.move(tight.card.left + 20, tight.card.top + 20); await page.mouse.down(); await page.mouse.up()
    expect(await deckInline(deck)).toEqual([expect.any(String), expect.any(String), false, true])
    expect((await measureChat(page)).thread.height).toBeLessThan(44)
  } finally { await constrainChat(page, '') }
  await expect.poll(async () => (await measureChat(page)).suspended).toBe(false)
  await expect.poll(async () => packedBlocks(await measureChat(page)).reasons).toEqual([])
  expect((await measureChat(page)).card.height).toBeCloseTo(roomy.card.height, 0)

  await resize(800, 560); await sidebar(false); await settle()
  await bounded()
  const small = await measureChat(page)
  expect(packedBlocks(small).reasons, 'four cards in the smallest window').toEqual([])
  await dragBy(page, card, -60, -40); await idle()
  const moved = await measureChat(page)
  expect(packedBlocks(moved).reasons, 'dragged in the smallest window').toEqual([])
  expect(moved.card.left).toBeLessThan(small.card.left - 30)
  await resize(1400, 900); await sidebar(true)
  await expect.poll(async () => (await measureChat(page)).chat.width).toBe(before.chat.width)
  await expect.poll(async () => packedBlocks(await measureChat(page)).reasons).toEqual([])

  const kept = await relative()
  await sendEvents(app, [appPreview(lane, ['second', 'third', 'fourth', 'fifth', 'sixth'], frame)])
  await expect(cards).toHaveCount(4)
  expect(await deck.evaluate(node => node.style.getPropertyValue('--deck-depth'))).toBe('3')
  const shown = await cards.evaluateAll(nodes => nodes.map(node => node.dataset.frame))
  const front = () => deck.locator('[data-position="0"]').getAttribute('data-frame')
  for (let index = 0; index < 6 && shown.includes(await front()); index++) { await deck.focus(); await page.keyboard.press('ArrowRight') }
  expect(shown).not.toContain(await front())
  await expect(cards).toHaveCount(4)
  await settle(); await bounded()
  await packed('front card from beyond the stack')
  expect(await relative()).toEqual(kept)
  await sendEvents(app, [appPreview(lane, ['second', 'third', 'fourth'], frame)])
  await expect(cards).toHaveCount(4)
  await expect.poll(relative).toEqual(kept)

  const primary = await grab(page, card)
  await page.mouse.move(primary.x + 40, primary.y + 20, { steps: 4 })
  const captured = await relative()
  near(captured.x, kept.x + 40)
  await secondPointer(deck, 7)
  expect(await relative()).toEqual(captured); await dragging()
  await page.mouse.move(primary.x + 60, primary.y + 30, { steps: 2 })
  near((await relative()).x, captured.x + 20)
  await page.mouse.up(); await idle()
  const committed = await relative()
  const errors = []
  page.on('pageerror', error => errors.push(String(error)))
  await withRefusedCapture(deck, async () => {
    const refused = await grab(page, card)
    await page.mouse.move(refused.x + 50, refused.y + 50, { steps: 3 })
    await idle()
    expect(await relative()).toEqual(committed)
    await page.mouse.up()
  })
  expect(errors).toEqual([])
  await dragBy(page, card, -30, 10)
  near((await relative()).x, committed.x - 30)

  await sendEvents(app, [appPreview(lane, ['second'], frame)])
  await expect(cards).toHaveCount(2)
  await dragTo(page, card, { x: 0, y: 0 }, 10)
  const corner = await relative()
  near(corner.x, 30); near(corner.y, 30)
  const press = await grab(page, card)
  await page.mouse.move(press.x + 40, press.y + 40, { steps: 4 })
  near((await relative()).x, 70)
  await sendEvents(app, [appPreview(lane, ['second'], plain, Date.now() + 1)])
  await expect(deck.locator('[data-frame="second"] img')).toHaveAttribute('src', `data:image/png;base64,${plain.data}`)
  await dragging(); near((await relative()).y, 70)
  await sendEvents(app, [appPreview(lane, ['second', 'third', 'fourth'], plain)])
  await expect(cards).toHaveCount(4)
  await settle(); await bounded()
  await expect.poll(async () => (await relative()).x).toBeCloseTo(90, 0)
  near((await relative()).y, 90); await dragging()
  await page.mouse.move(press.x + 41, press.y + 41)
  near((await relative()).x, 91); near((await relative()).y, 91)
  await page.mouse.move(press.x + 141, press.y + 141, { steps: 4 })
  await expect.poll(async () => (await relative()).y).toBeCloseTo(191, 0)
  near((await relative()).x, 191)
  await page.mouse.up(); await idle()
  await packed('stack grew during a drag')

  const chosenA = await relative()
  const switching = await grab(page, card)
  await page.mouse.move(switching.x + 50, switching.y + 50, { steps: 4 })
  await dragging()
  await row(other.name).evaluate(node => node.click())
  await expect(card).toHaveAttribute('data-lane', `bot-${other.id}`)
  await settle(); await page.mouse.up(); await idle()
  expect(await relative()).toEqual(otherPosition)
  await row(BOT).click()
  await expect(card).toHaveAttribute('data-lane', lane)
  await settle(); await expect.poll(relative).toEqual(chosenA); await idle()
  for (let index = 0; index < 4 && await card.getAttribute('data-source') !== 'web'; index++) { await deck.focus(); await page.keyboard.press('ArrowRight') }
  await expect(card).toHaveAttribute('data-source', 'web')
  await card.hover(); await card.locator('.preview-card-actions button').first().click()
  await expect(page.getByTestId('live-address')).toBeVisible()
  await page.getByTestId('composer-web').evaluate(node => node.click())
  await expect(page.getByTestId('live-address')).toHaveCount(0)

  await row(solo.name).click()
  await expect(deck).toHaveCount(0)
  await sendEvents(app, [appPreview(soloLane, ['alpha'], frame)])
  await visible(); expect(await deckInline(deck)).toEqual(['', '', false, false])
  await expect(card).toHaveAttribute('data-source', 'app')
  await dragAcross(page, card, () => packed('app-only lane drag'))
  const soloChoice = await relative()
  await sendEvents(app, [appPreview(soloLane, [], frame)])
  await expect(deck).toHaveCount(0)
  await expect(page.locator('.preview-card-reopen')).toHaveCount(0)
  await sendEvents(app, [appPreview(soloLane, ['alpha'], frame)])
  await visible(); await expect.poll(relative).toEqual(soloChoice)
  const gone = await grab(page, card)
  await page.mouse.move(gone.x - 60, gone.y - 40, { steps: 4 })
  await sendEvents(app, [appPreview(soloLane, [], frame)])
  await expect(deck).toHaveCount(0); await page.mouse.up()
  await sendEvents(app, [appPreview(soloLane, [{ id: 'alpha', data: undefined, unavailable: true, captureReason: 'screen_recording_denied' }], frame)])
  await visible(); await expect.poll(relative).toEqual(soloChoice)
  await expect(card.locator('.preview-card-stage')).toHaveAttribute('data-phase', 'unavailable')
  await expect(card.locator('.preview-card-state')).toBeVisible()
  await packed('unavailable app frame')
  await dragBy(page, card, -60, -40); await idle()
  near((await relative()).x, soloChoice.x - 60); near((await relative()).y, soloChoice.y - 40)
  await sendEvents(app, [appPreview(soloLane, ['alpha'], plain, Date.now() + 2)])
  await expect(card.locator('.preview-card-stage')).toHaveAttribute('data-phase', 'ready')
  await expect(card.locator('.preview-card-stage img')).toHaveAttribute('src', `data:image/png;base64,${plain.data}`)
  await packed('after the app frame recovered')

  await page.reload()
  await openActivity(page, 'bots'); await row(BOT).click()
  await showWebFrame(app, { lane, url: URL, frame })
  await expectPainted(card, frame, expect); await settle()
  expect(await deck.evaluate(node => [node.style.left, node.style.top, node.hasAttribute('data-dragging'), node.hasPointerCapture(1)])).toEqual(['', '', false, false])
  expect(await relative()).toEqual(anchored)
  await dragAcross(page, card, () => packed('after a renderer restart')); await idle()
  const restarted = await measureChat(page)
  expect(packedBlocks(restarted).reasons, 'after a renderer restart').toEqual([])
  expect(restarted.card.left).toBeLessThan(before.card.left - 100)

  const point = ({ x, y }) => `${Math.round(x)},${Math.round(y)}`
  return {
    ok: true,
    evidence: `agent:frame ${frame.width}x${frame.height} png painted preview-card for ${lane} with no web pane; ${describeBlocks(before)}; `
      + `drag ${point(drag.from)} to ${point(drag.to)}: moved and clamped; untouched four-card bounds at 800x560 and 1400x600, tab/blur/cancel, cancel before the first drag, reopen position, mid-drag resize with 1px follow-up, incoming-frame drag, resize anchors, stacked depth bounds, lane positions, popover dismissal, chosen spot after shrink and stack changes, composer floor at 600px and under a growing draft, `
      + `fitted 150px thread and suspended 30px thread, 800x560 window, six-frame cap, second pointer ignored, refused capture, frame replaced and stack grown mid-drag, lane switch mid-drag, app-only deck torn down and restored, unavailable frame recovered, renderer restart, and native animations verified; after: ${describeBlocks(after)}`,
  }
}
