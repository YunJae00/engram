/* global document, window, PointerEvent, getComputedStyle */
import { createBot, appendBotTurn } from '../../packages/core/src/index.ts'
import { deckPlace, describeBlocks, flowGeometry, measureChat, packedBlocks, settle, stackExposed } from './lib/chat-layout.mjs'
import { appFrames, pngFrame, showWebFrame, sendEvents } from './lib/frame-fixture.mjs'

const BOT = 'Live overlay'
const OTHER = 'Other overlay lane'
const URL = 'https://example.test/live'

export async function run(page, { app, paths, expect, openActivity }) {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const bot = await createBot(paths, { name: BOT, purpose: '' })
  const other = await createBot(paths, { name: OTHER, purpose: '' })
  for (const role of ['user', 'assistant']) await appendBotTurn(paths, bot.id, { role, text: `Overlay geometry ${role}`, at: new Date().toISOString() })
  const resize = async (width, height) => {
    await app.evaluate(({ BrowserWindow }, [width, height]) => BrowserWindow.getAllWindows()[0].setSize(width, height), [width, height])
    await expect.poll(() => page.evaluate(() => [window.innerWidth, window.innerHeight])).toEqual([width, height])
    await settle(page)
  }
  const corner = async (end) => {
    const { chat } = await measureChat(page)
    return end ? dragTo(chat.right - 4, chat.bottom - 4) : dragTo(chat.left + 4, chat.top + 4)
  }
  const watchPointers = () => page.evaluate(() => window.addEventListener('pointerdown', event => { window.overlayPointer = event.pointerId }, true))
  // A window never shown paints once a second under Xvfb; shown inactive it runs at full rate without taking focus.
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].showInactive())
  await resize(1400, 900)
  await page.reload()
  await watchPointers()
  await openActivity(page, 'bots')
  const choose = (name) => page.locator('.bots-row', { hasText: name }).click()
  await choose(BOT)
  const lane = `bot-${bot.id}`, otherLane = `bot-${other.id}`
  const frame = pngFrame({ width: 1280, height: 800 })
  const card = page.getByTestId('preview-card')
  const deck = page.getByTestId('preview-deck')
  const shift = () => deck.evaluate(node => node.style.translate)
  const packed = async (label, options) => expect(packedBlocks(await measureChat(page), options).reasons, label).toEqual([])

  await showWebFrame(app, { lane, url: URL, frame })
  await expect(card).toBeVisible()
  await expect(card.locator('canvas')).toHaveAttribute('data-painted', '', { timeout: 15_000 })
  await expect(card.locator('canvas')).toHaveAttribute('data-format', 'png')
  await expect(page.getByTestId('live-address')).toHaveCount(0)
  await expect(card.locator('.preview-card-label')).toContainText('example.test')
  expect(await card.locator('canvas').evaluate(canvas => [canvas.width, canvas.height])).toEqual([frame.width, frame.height])
  expect(await card.locator('canvas').evaluate(canvas => [...canvas.getContext('2d').getImageData(256, 320, 1, 1).data])).toEqual([220, 60, 60, 255])
  expect(await card.evaluate(node => getComputedStyle(node).animationName)).toBe('preview-card-in')
  await settle(page)
  await packed('untouched card above the thread', { slotted: true })
  const before = await measureChat(page)
  const baseline = await flowGeometry(page)
  const unshifted = async (label) => expect(await flowGeometry(page), label).toEqual(baseline)

  const begin = async () => {
    const box = await card.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    return box
  }
  const dragTo = async (x, y) => {
    await begin()
    await page.mouse.move(x, y, { steps: 4 })
    await page.mouse.up()
    await settle(page)
  }

  for (const [trigger, menu] of [[page.getByTestId('workspace-switcher'), 'workspace-menu'], [page.locator('.bots-chat').getByTestId('model-picker'), 'model-picker-menu']]) {
    await trigger.click()
    await expect(page.getByTestId(menu)).toBeVisible()
    await begin()
    await page.mouse.up()
    await expect(page.getByTestId(menu)).toHaveCount(0)
    expect(await shift(), `${menu} press without movement`).toBe('')
  }

  const from = await begin()
  await page.mouse.move(from.x + from.width * 0.2, from.y + from.height / 2, { steps: 4 })
  await expect(deck).toHaveAttribute('data-dragging', '')
  await unshifted('mid drag')
  await page.mouse.move(from.x - from.width * 0.5 + from.width / 2, from.y + from.height * 1.2 + from.height / 2, { steps: 4 })
  await unshifted('mid drag over the thread')
  await page.mouse.up()
  await expect(deck).not.toHaveAttribute('data-dragging')
  const after = await measureChat(page)
  expect(packedBlocks(after).reasons, 'after the drag').toEqual([])
  expect(Math.abs(after.card.left - (before.card.left - before.card.width * 0.5))).toBeLessThan(2)
  expect(Math.abs(after.card.top - (before.card.top + before.card.height * 1.2))).toBeLessThan(2)
  expect(after.cardOnTop).toBe(true)
  await unshifted('after the drag')
  expect(await page.evaluate(() => document.getSelection().toString())).toBe('')
  const origin = await card.boundingBox()
  await page.mouse.move(500, 500)
  expect(await card.boundingBox()).toEqual(origin)

  for (const cancellation of ['Escape', 'pointercancel', 'lostpointercapture', 'blur', 'tab']) {
    await begin()
    await page.mouse.move(origin.x + 80, origin.y + 30)
    const id = await page.evaluate(() => window.overlayPointer)
    if (cancellation === 'tab') {
      await page.getByTestId('workspace-switcher').evaluate(node => node.click())
      await page.getByTestId('activity-list').evaluate(node => node.click())
      await expect(card).toBeHidden()
      await openActivity(page, 'bots')
      await expect(card).toBeVisible()
    }
    else if (cancellation === 'blur') await page.evaluate(() => window.dispatchEvent(new Event('blur')))
    else if (cancellation === 'Escape') await page.keyboard.press('Escape')
    else if (cancellation === 'lostpointercapture') await deck.evaluate((node, id) => node.releasePointerCapture(id), id)
    else await deck.evaluate((node, id) => node.dispatchEvent(new PointerEvent('pointercancel', { pointerId: id, bubbles: true })), id)
    await page.mouse.up()
    await settle(page)
    expect(await card.boundingBox(), cancellation).toEqual(origin)
    await expect(deck).not.toHaveAttribute('data-dragging')
    await unshifted(cancellation)
  }

  await deck.evaluate(node => { node.setPointerCapture = () => { throw new Error('capture refused') } })
  try {
    await begin()
    await expect(deck).not.toHaveAttribute('data-dragging')
    await page.mouse.move(origin.x + 120, origin.y + 60, { steps: 4 })
    await page.mouse.up()
    expect(await card.boundingBox(), 'refused capture').toEqual(origin)
  } finally {
    await deck.evaluate(node => { delete node.setPointerCapture })
  }

  await begin()
  await page.mouse.move(origin.x + 40, origin.y + 40)
  const second = await deckPlace(page)
  await deck.evaluate(node => {
    for (const type of ['pointerdown', 'pointermove', 'pointerup', 'pointercancel']) node.dispatchEvent(new PointerEvent(type, { pointerId: 77, isPrimary: false, button: 0, clientX: 5, clientY: 5, bubbles: true }))
  })
  await expect(deck).toHaveAttribute('data-dragging', '')
  expect(await deckPlace(page), 'second pointer').toEqual(second)
  await page.mouse.move(origin.x + 41, origin.y + 40)
  expect((await deckPlace(page)).x).toBeCloseTo(second.x + 1, 0)
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await settle(page)
  expect(await card.boundingBox()).toEqual(origin)

  await corner(false)
  let clamped = await measureChat(page)
  expect(clamped.card.left).toBeCloseTo(clamped.chat.left, 0)
  expect(clamped.card.top).toBeCloseTo(clamped.chat.top, 0)
  await corner(true)
  clamped = await measureChat(page)
  expect(clamped.card.right).toBeCloseTo(clamped.chat.right, 0)
  expect(Math.abs(clamped.card.bottom - clamped.thread.bottom)).toBeLessThanOrEqual(1)
  expect(packedBlocks(clamped).reasons, 'parked at the bottom').toEqual([])
  await unshifted('parked at the bottom')
  await dragTo(origin.x + origin.width / 2, origin.y + origin.height / 2)
  const restored = await card.boundingBox()
  for (const [index, testId] of [[1, 'preview-card-collapsed'], [2, 'preview-card-reopen']]) {
    await card.hover()
    await card.locator('.preview-card-actions button').nth(index).click()
    await expect(card).toHaveCount(0)
    await page.getByTestId(testId).click()
    await expect(card).toBeVisible()
    await settle(page)
    expect(await card.boundingBox(), `${testId} reopened`).toEqual(restored)
    await unshifted(`${testId} reopened`)
  }

  const chosen = await deckPlace(page)
  for (const width of [1100, 1600, 1400]) {
    await resize(width, 900)
    await expect.poll(async () => packedBlocks(await measureChat(page)).reasons, `width ${width}`).toEqual([])
  }
  await expect.poll(() => deckPlace(page)).toEqual(chosen)

  await begin()
  await page.mouse.move(restored.x + restored.width / 2 + 80, restored.y + restored.height / 2 + 30)
  const held = await deckPlace(page)
  await sendEvents(app, [appFrames(lane, ['second'], frame)])
  await expect(deck.locator('.preview-deck-card')).toHaveCount(2)
  await expect(card).toHaveAttribute('data-source', 'app')
  await settle(page)
  await expect(deck).toHaveAttribute('data-dragging', '')
  expect(await deck.evaluate((node, id) => node.hasPointerCapture(id), await page.evaluate(() => window.overlayPointer))).toBe(true)
  expect(await deckPlace(page), 'incoming frame while held').toEqual(held)
  await sendEvents(app, [appFrames(lane, ['second'], pngFrame({ width: 640, height: 400 }))])
  await page.mouse.move(restored.x + restored.width / 2 + 100, restored.y + restored.height / 2 + 50)
  expect((await deckPlace(page)).x).toBeCloseTo(held.x + 20, 0)
  await page.mouse.up()
  await deck.focus()
  await page.keyboard.press('ArrowRight')
  await expect(card).toHaveAttribute('data-source', 'web')
  await page.keyboard.press('ArrowLeft')
  await expect(card).toHaveAttribute('data-source', 'app')
  await settle(page)
  expect(await deck.locator('[data-position="0"]').evaluate(node => getComputedStyle(node).animationName)).toBe('preview-deck-forward')

  await corner(false)
  await expect.poll(() => deckPlace(page)).toEqual(expect.objectContaining({ x: 30, y: 30 }))
  const saved = await deckPlace(page)
  await sendEvents(app, [appFrames(lane, ['second', 'third', 'fourth', 'fifth', 'sixth'], frame)])
  await expect(deck.locator('.preview-deck-card')).toHaveCount(4)
  await settle(page)
  await expect.poll(() => stackExposed(page), 'four cards near the corner').toBe('')
  await expect.poll(() => deckPlace(page)).toEqual(expect.objectContaining({ x: 90, y: 90 }))
  const seen = new Set()
  for (let index = 0; index < 6; index++) {
    seen.add(await deck.locator('[data-position="0"]').getAttribute('data-frame'))
    await deck.focus()
    await page.keyboard.press('ArrowRight')
    await settle(page)
    expect(await stackExposed(page), `cycled ${index}`).toBe('')
  }
  expect(seen.size).toBe(6)
  await sendEvents(app, [appFrames(lane, [], frame)])
  await expect(deck.locator('.preview-deck-card')).toHaveCount(1)
  await expect.poll(() => deckPlace(page), 'stack removed').toEqual(saved)

  await resize(1400, 600)
  await corner(true)
  const parked = await measureChat(page)
  expect(packedBlocks(parked).reasons, 'parked at the bottom of a short window').toEqual([])
  expect(Math.abs(parked.card.bottom - parked.thread.bottom)).toBeLessThanOrEqual(1)
  await page.getByTestId('bots-input').fill('one\ntwo\nthree\nfour')
  await expect.poll(async () => (await measureChat(page)).thread.bottom).toBeLessThan(parked.thread.bottom - 40)
  await expect.poll(async () => packedBlocks(await measureChat(page)).reasons, 'composer grew under a parked card').toEqual([])
  await page.getByTestId('bots-input').fill('')
  await expect.poll(async () => (await measureChat(page)).card.top).toBeCloseTo(parked.card.top, 0)
  await sendEvents(app, [appFrames(lane, ['second', 'third', 'fourth'], frame)])
  await expect(deck.locator('.preview-deck-card')).toHaveCount(4)
  await settle(page)
  await expect.poll(() => stackExposed(page), 'four cards in a short window').toBe('')
  await sendEvents(app, [appFrames(lane, [], frame)])
  await resize(1400, 900)
  await dragTo(restored.x + restored.width / 2, restored.y + restored.height / 2)
  const laneSpot = await deckPlace(page)

  await choose(OTHER)
  await sendEvents(app, [appFrames(otherLane, ['solo'], frame)])
  await expect(card).toBeVisible()
  await settle(page)
  await packed('fresh lane untouched', { slotted: true })
  await begin()
  await page.mouse.up()
  expect(await shift(), 'click keeps a fresh lane untouched').toBe('')
  await begin()
  await page.mouse.move(400, 400, { steps: 4 })
  await page.keyboard.press('Escape')
  await page.mouse.up()
  expect(await shift(), 'cancelled first drag').toBe('')
  await resize(1100, 900)
  await packed('fresh lane after resize', { slotted: true })
  await resize(1400, 900)
  await dragTo(500, 500)
  const otherSpot = await deckPlace(page)
  await begin()
  await page.mouse.move(700, 300, { steps: 4 })
  await page.locator('.bots-row', { hasText: BOT }).evaluate(node => node.click())
  await page.mouse.up()
  await expect(card).toBeVisible()
  await settle(page)
  await expect.poll(() => deckPlace(page), 'first lane keeps its spot').toEqual(laneSpot)
  await expect(deck).not.toHaveAttribute('data-dragging')
  await choose(OTHER)
  await sendEvents(app, [appFrames(otherLane, ['solo'], frame)])
  await expect(card).toBeVisible()
  await settle(page)
  await expect.poll(() => deckPlace(page), 'dropped lane-switch drag').toEqual(otherSpot)

  await sendEvents(app, [appFrames(otherLane, ['solo'], frame, { data: undefined, captureState: 'unavailable', captureReason: 'screen_recording_denied' })])
  await expect(card.locator('.preview-card-state')).toBeVisible()
  await expect(card.locator('img')).toHaveCount(0)
  await dragTo(600, 400)
  const unavailableSpot = await deckPlace(page)
  expect(unavailableSpot).not.toEqual(otherSpot)
  expect(packedBlocks(await measureChat(page)).reasons, 'unavailable frame').toEqual([])
  await sendEvents(app, [appFrames(otherLane, ['solo'], frame)])
  await expect(card.locator('img')).toBeVisible()
  expect(await deckPlace(page)).toEqual(unavailableSpot)
  await sendEvents(app, [appFrames(otherLane, [], frame)])
  await expect(deck).toHaveCount(0)
  await sendEvents(app, [appFrames(otherLane, ['solo'], frame)])
  await expect(card).toBeVisible()
  await settle(page)
  await expect.poll(() => deckPlace(page), 'remounted deck').toEqual(unavailableSpot)
  await begin()
  await page.mouse.move(300, 300, { steps: 4 })
  await sendEvents(app, [appFrames(otherLane, [], frame)])
  await expect(deck).toHaveCount(0)
  await page.mouse.up()
  await sendEvents(app, [appFrames(otherLane, ['solo'], frame)])
  await expect(card).toBeVisible()
  await settle(page)
  await expect.poll(() => deckPlace(page), 'cleared while held').toEqual(unavailableSpot)

  await page.reload()
  await watchPointers()
  await openActivity(page, 'bots')
  await choose(OTHER)
  await sendEvents(app, [appFrames(otherLane, ['solo'], frame)])
  await expect(card).toBeVisible()
  await settle(page)
  await packed('after reload', { slotted: true })
  await expect(deck).not.toHaveAttribute('data-dragging')
  await dragTo(500, 500)
  expect(await shift(), 'drag after reload').not.toBe('')

  await choose(BOT)
  await showWebFrame(app, { lane, url: URL, frame })
  await expect(card).toHaveAttribute('data-source', 'web')
  await card.hover()
  await card.locator('.preview-card-actions button').first().click()
  await expect(page.getByTestId('live-address')).toBeVisible()
  expect(errors, 'page errors').toEqual([])

  return {
    ok: true,
    evidence: `agent:frame ${frame.width}x${frame.height} png painted preview-card for ${lane} with no web pane; untouched ${describeBlocks(before)} stays above the thread; `
      + `dragged ${describeBlocks(after)} with the thread unchanged; menu dismissal, escape/cancel/lostcapture/blur/tab cancellations, refused capture, second pointer, corner and composer-floor clamps, `
      + 'reopen position, incoming frames while held, resize anchors, stacked depth bounds with six frames, short window and growing draft, lane spots and lane-switch drop, '
      + 'unavailable frame, empty-frame remounts, reload reset and native animations verified',
  }
}
