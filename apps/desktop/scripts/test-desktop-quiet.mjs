import assert from 'node:assert/strict'

export async function testDesktopQuiet(helper, fixture, target, until) {
  await helper.ready
  await helper.request('inspectWindow', { window: target.window, pid: 0 })
  await fixture.request('away')
  await fixture.request('minimizeQuiet')
  assert.equal((await helper.request('quietState', target)).minimized, true)
  const scan = () => helper.request('quietScan', target)
  const first = await scan()
  assert.equal(first.state.minimized, false, 'Quiet reads restore an owned minimized window')
  assert.match(first.snapshot, /^[a-f0-9]{32}$/)
  assert(first.controls.every(control => /^c[0-9]+$/.test(control.id)))
  const entry = first.controls.find(control => control.name === 'Worker input')
  const button = first.controls.find(control => control.name === 'Count click')
  assert.ok(entry?.can.set)
  assert.ok(button?.can.press)
  assert.equal((await fixture.request('state')).foreground, false)
  const field = { ...target, snapshot: first.snapshot, control: entry.id }
  await helper.request('listWindows', {})
  assert.equal((await helper.request('quietRead', field)).text, (entry.value ?? '').trim(), 'Listing windows must preserve the current snapshot')
  await fixture.request('focus')
  await fixture.request('foreignInput')
  await assert.rejects(helper.request('quietSet', { ...field, text: 'Do not interrupt' }), /person is using/)
  await fixture.request('away')
  await until(() => helper.request('quietState', target), state => state.idleMs >= 4000, 'Owned input did not settle')
  const set = await helper.request('quietSet', { ...field, text: 'Quiet draft' })
  assert.equal(set.exact, true)
  assert.equal(set.foregroundChanged, false, 'Owned background value provider must preserve foreground')
  assert.equal((await fixture.request('state')).foreground, set.foregroundChanged, 'Set receipt must report provider activation')
  await assert.rejects(helper.request('quietSet', { ...field, text: 'Overwrite' }), /already holds text/)
  await assert.rejects(helper.request('quietSet', { ...field, text: 'Overwrite', expected: 'Quiet  draft' }), /already holds text/)
  assert.equal((await helper.request('quietRead', field)).text, 'Quiet draft')
  assert.equal((await helper.request('quietSet', { ...field, text: 'Reviewed draft', expected: 'Quiet draft' })).landed, true)
  await assert.rejects(helper.request('quietSet', { ...field, snapshot: '0'.repeat(32), text: 'Wrong snapshot' }), /snapshot/)
  await fixture.request('away')
  const press = await helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id })
  assert.equal(press.foregroundChanged, false, 'Owned background invoke provider must preserve foreground')
  await until(() => fixture.request('state'), state => state.clicks === 1, 'Quiet invoke did not reach the button')
  assert.equal((await fixture.request('state')).foreground, press.foregroundChanged, 'Provider activation must be reported honestly')
  await fixture.request('away')
  await fixture.request('quietRename')
  await assert.rejects(helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id }), /control changed/)

  await fixture.request('dense')
  const dense = await scan()
  assert.ok(dense.skippedTexts > 0)
  assert.ok(JSON.stringify(dense).length < 60000)
  await fixture.request('sparse')

  await fixture.request('quietProtected')
  await fixture.request('away')
  const protectedView = await scan()
  const protectedField = protectedView.controls.find(control => control.name === 'Account field')
  const protectedButton = protectedView.controls.find(control => control.name === 'Continue account')
  assert.ok(protectedField && protectedButton)
  await assert.rejects(helper.request('quietSet', { ...target, snapshot: protectedView.snapshot, control: protectedField.id, text: 'Do not enter' }), /manual control/)
  await assert.rejects(helper.request('quietPress', { ...target, snapshot: protectedView.snapshot, control: protectedButton.id }), /manual control/)
  await fixture.request('sparse')

  await fixture.request('password')
  await fixture.request('away')
  await assert.rejects(scan(), /manual control/)
  await assert.rejects(helper.request('quietRead', target), /manual control/)
  await assert.rejects(helper.request('quietSet', { ...field, text: 'Do not enter', expected: 'Reviewed draft' }), /manual control/)
  await assert.rejects(helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id }), /manual control/)
  await fixture.request('hidePassword')
  await fixture.request('quietReset')
  const beforeReselect = await scan()
  const oldField = beforeReselect.controls.find(control => control.name === 'Worker input')
  assert.ok(oldField)
  await helper.request('inspectWindow', { window: target.window, pid: 0 })
  assert.equal((await helper.request('quietRead', { ...target, snapshot: beforeReselect.snapshot, control: oldField.id })).text, (oldField.value ?? '').trim(), 'Another chat inspecting the same window must preserve its unchanged controls')
  return { readWithoutFocus: true, providerOnlySet: true, setActivatedWindow: set.foregroundChanged, providerOnlyPress: true, pressActivatedWindow: press.foregroundChanged, exactReplacement: true, protectedSurfaceRejected: true, passwordRejected: true }
}
