import assert from 'node:assert/strict'
import { desktopFailure } from '../src/main/desktop-failure.ts'

export async function testDesktopQuiet(helper, fixture, target, until, launchApp) {
  await helper.ready
  await helper.request('inspectWindow', { window: target.window, pid: 0 })
  await fixture.request('away')
  const previous = (await fixture.request('state')).foregroundWindow
  const opened = await helper.request('openApp', { app: launchApp.id })
  assert.equal(opened.requested, true)
  assert.equal(typeof opened.foregroundRestored, 'boolean')
  assert.equal((await fixture.request('state')).foregroundWindow, previous, 'openApp must preserve or restore the owned foreground window')
  console.log(JSON.stringify({ quietOpenApp: opened }))
  await fixture.request('awayEscape')
  await until(() => helper.request('inputState'), state => state.escaped, 'Owned Escape input was not observed')
  assert.equal((await helper.request('quietState', target)).minimized, false, 'Escape in another window must not poison a fresh background read')
  await helper.request('stop')
  await helper.request('quietScan', target)
  await fixture.request('minimizeQuiet')
  assert.equal((await helper.request('quietState', target)).minimized, true)
  const scan = () => helper.request('quietScan', target)
  const first = await scan()
  assert.equal(first.state.minimized, false, 'Quiet reads restore an owned minimized window')
  assert.match(first.snapshot, /^[a-f0-9]{32}$/)
  assert(first.controls.every(control => /^c[0-9]+$/.test(control.id)))
  const entry = first.controls.find(control => control.name === 'Worker input')
  const button = first.controls.find(control => control.name === 'Count click')
  assert.ok(entry?.can.set)
  const nodes = [...first.controls, ...first.texts]
  assert.ok(entry.parent, 'Sorted input must retain its owning container')
  assert.ok(nodes.some(node => node.id === entry.parent), 'Input owner must be present in the unfiltered observation')
  assert.ok(nodes.every(node => Number.isInteger(node.order)), 'Observation order survives control/text separation')
  assert.ok(button?.can.press)
  assert.equal((await fixture.request('state')).foreground, false)
  await until(() => helper.request('quietState', target), state => state.idleMs >= 4000, 'Owned same-process input must settle before provider actions')
  const postedControl = first.controls.find(control => control.name === 'Posted click target')
  assert.ok(postedControl?.can.press, 'No-Invoke control must offer background press')
  const postedBefore = (await fixture.request('state')).postedClicks
  const posted = await helper.request('quietPress', { ...target, snapshot: first.snapshot, control: postedControl.id })
  assert.equal(posted.pressed, 'posted', 'No-Invoke control must use process messages')
  assert.equal(posted.requiresVerification, true)
  await until(() => fixture.request('state'), state => state.postedClicks === postedBefore + 1, 'Owned no-Invoke control did not receive posted click')
  assert.equal((await fixture.request('state')).foregroundWindow, previous, 'Posted click must preserve foreground')
  console.log(JSON.stringify({ quietPostedClick: posted }))
  const option = first.controls.find(control => control.name === 'Fixture option')
  assert.equal(option?.state.checked, 'off')
  const chosen = { ...target, snapshot: first.snapshot, control: option.id, state: 'checked' }
  const enabled = await helper.request('quietPress', chosen)
  console.log(JSON.stringify({ quietDesiredState: enabled }))
  assert.equal(enabled.foregroundChanged, false, 'Owned checkbox state change must preserve foreground')
  assert.equal(enabled.satisfied, true)
  assert.equal(enabled.after.checked, 'on')
  const enabledAgain = await helper.request('quietPress', chosen)
  assert.equal(enabledAgain.pressed, 'none')
  assert.equal(enabledAgain.after.checked, 'on', 'Enabling an enabled option must not toggle it off')
  assert.equal((await fixture.request('state')).foreground, false, 'Desired-state action must preserve foreground in the owned fixture')
  const lastItem = first.controls.find(control => control.name === 'Fixture item 39')
  assert.ok(lastItem?.can.scrollIntoView, 'Owned list item exposes background scroll-into-view')
  const scrolled = await helper.request('quietPress', { ...target, snapshot: first.snapshot, control: lastItem.id, action: 'scroll_into_view' })
  console.log(JSON.stringify({ quietScroll: scrolled }))
  assert.equal(scrolled.satisfied, true)
  assert.equal(scrolled.foregroundChanged, false)
  const selected = await helper.request('quietPress', { ...target, snapshot: first.snapshot, control: lastItem.id, state: 'selected' })
  console.log(JSON.stringify({ quietSelected: selected }))
  assert.equal(selected.foregroundChanged, false)
  assert.equal(selected.after.selected, true)
  const list = first.controls.find(control => control.name === 'Fixture list')
  assert.ok(list?.can.scroll)
  const moved = await helper.request('quietPress', { ...target, snapshot: first.snapshot, control: list.id, action: 'scroll_up' })
  assert.equal(moved.satisfied, true)
  assert.equal(moved.foregroundChanged, false)
  const clicksBefore = (await fixture.request('state')).clicks
  await fixture.request('blockOwnedUi')
  const blockedRead = helper.request('quietScan', target)
  const expired = helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id, expiresAt: Date.now() + 50 })
  await assert.rejects(expired, /before execution; it was not run/)
  await blockedRead
  assert.equal((await fixture.request('state')).clicks, clicksBefore, 'An expired queued press must never run later')
  await fixture.request('blockOwnedUi')
  const secondRead = helper.request('quietScan', target)
  const cancelledId = helper.sequence + 1
  const cancelled = helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id })
  const notRun = assert.rejects(cancelled, /before execution; it was not run/)
  await helper.request('cancel', { target: cancelledId })
  await Promise.all([secondRead, notRun])
  assert.equal((await fixture.request('state')).clicks, clicksBefore, 'A cancelled queued press must never run later')
  const textRegion = first.controls.find(control => control.name === 'Scroll area')
  assert.ok(textRegion)
  const scoped = await helper.request('quietRead', { ...target, snapshot: first.snapshot, control: textRegion.id })
  assert.ok(scoped.text.includes('x'.repeat(60)), 'Reading a container must include its descendant text')
  assert.equal(scoped.scope, textRegion.id)
  const field = { ...target, snapshot: first.snapshot, control: entry.id }
  await helper.request('listWindows', {})
  assert.equal((await helper.request('quietRead', field)).text, (entry.value ?? '').trim(), 'Listing windows must preserve the current snapshot')
  await fixture.request('focus')
  await fixture.request('foreignInput')
  await assert.rejects(helper.request('quietSet', { ...field, text: 'Do not interrupt' }), /person is using/)
  await fixture.request('away')
  await until(() => helper.request('quietState', target), state => state.idleMs >= 4000, 'Owned input did not settle')
  const set = await helper.request('quietSet', { ...field, text: 'Quiet draft' })
  assert.equal(set.exact, true)
  assert.equal(set.foregroundChanged, false, 'Owned background value provider must preserve foreground')
  assert.equal((await fixture.request('state')).foreground, set.foregroundChanged, 'Set receipt must report provider activation')
  await assert.rejects(helper.request('quietSet', { ...field, text: 'Overwrite' }), /already holds text/)
  await assert.rejects(helper.request('quietSet', { ...field, text: 'Overwrite', expected: 'Quiet  draft' }), /already holds text/)
  assert.equal((await helper.request('quietRead', field)).text, 'Quiet draft')
  assert.equal((await helper.request('quietSet', { ...field, text: 'Reviewed draft', expected: 'Quiet draft' })).landed, true)
  await assert.rejects(helper.request('quietSet', { ...field, snapshot: '0'.repeat(32), text: 'Wrong snapshot' }), /snapshot/)
  await fixture.request('away')
  const press = await helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id })
  assert.equal(press.foregroundChanged, false, 'Owned background invoke provider must preserve foreground')
  await until(() => fixture.request('state'), state => state.clicks === 1, 'Quiet invoke did not reach the button')
  assert.equal((await fixture.request('state')).foreground, press.foregroundChanged, 'Provider activation must be reported honestly')
  await fixture.request('away')
  await fixture.request('delayNextClick')
  const activeId = helper.sequence + 1
  const active = helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id }).then(
    () => { throw new Error('Delayed owned action unexpectedly acknowledged before cancellation') }, error => error)
  await until(async () => fixture.events.some(event => event.type === 'ownedActionStarted'), value => value, 'Owned action did not start')
  await helper.request('cancel', { target: activeId })
  const uncertain = desktopFailure(await active)
  assert.equal(uncertain.delivery, 'delivery_uncertain')
  assert.equal(uncertain.retry, 'unsafe')
  assert.equal((await fixture.request('state')).clicks, 2, 'Cancellation after dispatch must not be claimed as unapplied or repeated')
  await fixture.request('away')
  await fixture.request('activateNextClick')
  const activated = await helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id })
  console.log(JSON.stringify({ quietSelfActivatingInvoke: activated }))
  assert.equal(activated.foregroundChanged, true, 'Self-activating Invoke must be reported')
  assert.equal(activated.foregroundRestored, true, 'Invoke must restore the previous foreground window')
  assert.equal((await fixture.request('state')).foreground, false, 'Owned foreground window must be restored')
  await fixture.request('away')
  await fixture.request('activateNextSet')
  const activatedSet = await helper.request('quietSet', { ...field, text: 'Read after restoration', expected: 'Reviewed draft' })
  assert.equal(activatedSet.foregroundChanged, true)
  assert.equal(activatedSet.foregroundRestored, true)
  await until(() => fixture.request('state'), state => !state.foreground, 'Set must restore owned foreground')
  await fixture.request('activateNextRead')
  const activatedRead = await helper.request('quietRead', target)
  assert.equal(activatedRead.foregroundChanged, true)
  assert.equal(activatedRead.foregroundRestored, true)
  await until(() => fixture.request('state'), state => !state.foreground, 'Read must restore owned foreground')
  console.log(JSON.stringify({ quietSelfActivatingSet: activatedSet, quietSelfActivatingRead: activatedRead }))
  await fixture.request('quietRename')
  await assert.rejects(helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id }), /control changed/)

  await fixture.request('dense')
  const outline = await helper.request('quietScan', { ...target, mode: 'skeleton' })
  assert.ok(outline.controls.every(control => control.depth <= 3))
  const region = outline.controls.find(control => control.childCount > 0 && !control.secret)
  assert.ok(region)
  const drilled = await helper.request('quietScan', { ...target, snapshot: outline.snapshot, root: region.id })
  assert.equal(drilled.root, region.id)
  await assert.rejects(helper.request('quietScan', { ...target, snapshot: '0'.repeat(32), root: region.id }), /snapshot/)
  const dense = await scan()
  assert.ok(dense.truncated)
  assert.ok(JSON.stringify(dense).length < 60000)
  await fixture.request('sparse')

  await fixture.request('quietDeep')
  const cut = await scan()
  assert.equal(cut.truncated, true)
  const deep = await helper.request('quietScan', { ...target, find: 'Deep input' })
  assert.equal(deep.searchComplete, true)
  assert.equal(deep.controls.length, 1, 'Targeted search must not retain unrelated editors')
  const inserted = await helper.request('quietSet', { ...target, snapshot: deep.snapshot, control: deep.controls[0].id, text: 'Owned deep draft' })
  assert.equal(inserted.landed, true, 'Whitespace-only content is empty')
  assert.ok(inserted.nearby.some(button => button.name === 'Deep Send' && button.enabled && button.appeared))
  const prioritized = await scan()
  assert.ok(prioritized.controls.some(control => control.name === 'Deep Send'), 'The last edited neighborhood takes priority over the broad tree')
  const sending = await helper.request('quietScan', { ...target, find: 'Deep Send' })
  assert.equal(sending.searchComplete, true)
  assert.equal(sending.controls.length, 1)
  await fixture.request('sparse')

  await fixture.request('quietProtected')
  await fixture.request('away')
  const protectedView = await scan()
  const protectedField = protectedView.controls.find(control => control.name === 'Account field')
  const protectedButton = protectedView.controls.find(control => control.name === 'Continue account')
  assert.ok(protectedField && protectedButton)
  await assert.rejects(helper.request('quietSet', { ...target, snapshot: protectedView.snapshot, control: protectedField.id, text: 'Do not enter' }), /manual control/)
  await assert.rejects(helper.request('quietPress', { ...target, snapshot: protectedView.snapshot, control: protectedButton.id }), /manual control/)
  await fixture.request('sparse')

  await fixture.request('password')
  await fixture.request('away')
  await assert.rejects(scan(), /manual control/)
  await assert.rejects(helper.request('quietRead', target), /manual control/)
  await assert.rejects(helper.request('quietSet', { ...field, text: 'Do not enter', expected: 'Read after restoration' }), /manual control/)
  await assert.rejects(helper.request('quietPress', { ...target, snapshot: first.snapshot, control: button.id }), /manual control/)
  await fixture.request('hidePassword')
  await fixture.request('quietReset')
  const beforeReselect = await scan()
  const oldField = beforeReselect.controls.find(control => control.name === 'Worker input')
  assert.ok(oldField)
  await helper.request('inspectWindow', { window: target.window, pid: 0 })
  assert.equal((await helper.request('quietRead', { ...target, snapshot: beforeReselect.snapshot, control: oldField.id })).text, (oldField.value ?? '').trim(), 'Another chat inspecting the same window must preserve its unchanged controls')
  await fixture.request('history')
  const historyView = await helper.request('quietScan', { ...target, mode: 'skeleton', find: 'History region' })
  const history = historyView.controls.find(control => control.name === 'History region')
  assert.ok(history)
  const recent = await helper.request('quietRead', { ...target, snapshot: historyView.snapshot, control: history.id })
  for (let turn = 596; turn < 600; turn++) assert.ok(recent.text.includes(`Turn ${turn}`), 'Bounded text must retain the latest four turns of the scoped history')
  assert.ok(recent.text.indexOf('Turn 596') < recent.text.indexOf('Turn 599'), 'Recent turns remain in document order')
  assert.equal(recent.headClipped, true)
  assert.equal(recent.truncated, false)
  console.log(JSON.stringify({ recentTurns: { tail: recent.text.split('\n').slice(-4), headClipped: recent.headClipped, truncated: recent.truncated, scope: recent.scope } }))
  await fixture.request('clearHistory')
  for (const reveal of [true, false]) {
    const cold = await fixture.request(reveal ? 'chromiumCold' : 'chromiumSparse')
    await helper.request('inspectWindow', { window: cold.window, pid: 0 })
    await fixture.request('away')
    const warmed = await helper.request('quietScan', cold)
    assert.equal(warmed.accessibilityRescanned, true, 'Cold Chromium must complete one activation rescan')
    assert.equal(warmed.controls.some(control => control.name === 'Open conversation'), reveal)
    assert.equal((await fixture.request('chromiumState')).wakes, 1, 'Only one WM_GETOBJECT lParam=1 honeypot wake per cold scan')
    assert.equal((await fixture.request('state')).foreground, false, 'Accessibility activation must not take foreground')
    console.log(JSON.stringify({ ownedChromiumRescan: { reveal, nodes: warmed.controls.length + warmed.texts.length, ms: warmed.ms, truncated: warmed.truncated } }))
    await fixture.request('chromiumClose')
  }
  await helper.request('inspectWindow', { window: target.window, pid: 0 })
  return { readWithoutFocus: true, providerOnlySet: true, setActivatedWindow: set.foregroundChanged, providerOnlyPress: true, pressActivatedWindow: press.foregroundChanged, exactReplacement: true, protectedSurfaceRejected: true, passwordRejected: true }
}
